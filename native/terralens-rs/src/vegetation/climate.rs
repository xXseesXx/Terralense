//! TFC's forest climate noise used by `RegionChunkDataGenerator`.
//!
//! The seeds here follow the random stream in `region::Generator::new` and
//! TFC's `RegionChunkDataGenerator.create(long, ...)`, from the installed
//! TerraFirmaGreg Core 0.9.25 / TFC 3.2.25 bytecode.

use crate::{noise::OpenSimplex2D, random::Xoroshiro};

/// The two per-chunk climate fields used to choose forest trees and density.
pub(super) struct ForestNoise {
    density: OpenSimplex2D,
    weirdness: OpenSimplex2D,
}

impl ForestNoise {
    pub(super) fn new(world_seed: i64) -> Self {
        let mut world_random = Xoroshiro::new(world_seed);

        // Keep the exact draws made by RegionCore::new before it obtains its
        // chunk-data seed. Area construction consumes one seed for its base,
        // then two per zoom level (zoom and smooth).
        world_random.next_long(); // region generator
        world_random.next_long(); // cellular noise
        world_random.next_long(); // continental noise
        world_random.next_int(); // temperature noise
        world_random.next_int(); // rainfall noise
        consume_area_seeds(&mut world_random, 2); // biome area
        consume_area_seeds(&mut world_random, 3); // rock area
        let chunk_data_seed = world_random.next_long();

        // TFC RegionChunkDataGenerator.create reseeds this stream before
        // creating its independent fields. The preceding fields consume
        // five values before the two forest noise seeds.
        let mut chunk_random = Xoroshiro::new(chunk_data_seed);
        let reseed = chunk_data_seed ^ chunk_random.next_long();
        chunk_random.set_seed(reseed);
        chunk_random.next_long(); // rock layer area seed
        chunk_random.next_int(); // layer-height noise
        chunk_random.next_int(); // layer-skew X noise
        chunk_random.next_int(); // layer-skew Z noise
        chunk_random.next_long(); // forest biome-layer seed
        let weirdness_seed = chunk_random.next_int();
        let density_seed = chunk_random.next_int();

        let mut weirdness = OpenSimplex2D::from_int(weirdness_seed);
        weirdness.octaves(4).spread(0.0025f32 as f64);

        let mut density = OpenSimplex2D::from_int(density_seed);
        density
            .octaves(4)
            .spread(0.0025f32 as f64)
            .scaled(-0.2f32 as f64, 1.2f32 as f64);

        Self { density, weirdness }
    }

    /// Sample the forest density stored in TFC chunk data.
    ///
    /// TFC evaluates at the center of the chunk, scales OpenSimplex output
    /// from [-1, 1] to [-0.2, 1.2], clamps it to [0, 1], then stores an f32.
    #[inline]
    pub(super) fn density(&self, chunk_x: i32, chunk_z: i32) -> f32 {
        let (x, z) = chunk_center(chunk_x, chunk_z);
        self.density.sample(x, z).clamp(0.0, 1.0) as f32
    }

    /// Sample the forest weirdness stored in TFC chunk data.
    ///
    /// TFC maps the absolute OpenSimplex value by the f32 constant 1.1 and
    /// clamps the result before storing it as an f32.
    #[inline]
    pub(super) fn weirdness(&self, chunk_x: i32, chunk_z: i32) -> f32 {
        let (x, z) = chunk_center(chunk_x, chunk_z);
        (self.weirdness.sample(x, z).abs() * 1.100000023841858).clamp(0.0, 1.0) as f32
    }
}

#[inline]
fn chunk_center(chunk_x: i32, chunk_z: i32) -> (f64, f64) {
    (
        chunk_x.wrapping_mul(16).wrapping_add(8) as f64,
        chunk_z.wrapping_mul(16).wrapping_add(8) as f64,
    )
}

#[inline]
fn consume_area_seeds(random: &mut Xoroshiro, zoom_levels: usize) {
    random.next_long(); // base area seed
    for _ in 0..zoom_levels {
        random.next_long(); // zoom seed
        random.next_long(); // smooth seed
    }
}

/// TFC's elevation correction for average temperature (OverworldClimateModel).
#[inline]
pub(super) fn adjusted_average_temp_by_elevation(average_temp: f32, y: i32) -> f32 {
    if y <= 63 {
        return average_temp;
    }
    let cooling = ((y as f32 - 63.0) * 0.16225).clamp(0.0, 17.822);
    average_temp - cooling
}

#[cfg(test)]
mod tests {
    use super::{ForestNoise, adjusted_average_temp_by_elevation};

    #[test]
    fn forest_fields_match_installed_tfc_java_reference() {
        // Generated by tools/ForestNoiseReference.java with Minecraft 1.20.1
        // XoroshiroRandomSource and installed TFC 3.2.25 OpenSimplex2D.
        let fields = ForestNoise::new(7_787_531_943_268_589_495);
        let samples = [
            ((-141, -145), 0.658_450_305_f32, 0.238_416_433_f32),
            ((-130, -222), 0.511_670_172, 0.281_091_392),
            ((0, 0), 0.498_033_434, 0.012_133_805_1),
            ((31, -64), 0.507_604_361, 0.530_586_779),
            ((-1, 1), 0.483_599_871, 0.006_758_729_46),
        ];
        for ((chunk_x, chunk_z), expected_density, expected_weirdness) in samples {
            let density = fields.density(chunk_x, chunk_z);
            let weirdness = fields.weirdness(chunk_x, chunk_z);
            assert!((density - expected_density).abs() < 1.0e-7);
            assert!((weirdness - expected_weirdness).abs() < 1.0e-7);
        }
    }

    #[test]
    fn elevation_temperature_matches_tfc_clamp_boundaries() {
        assert_eq!(adjusted_average_temp_by_elevation(18.0, 63), 18.0);
        assert_eq!(adjusted_average_temp_by_elevation(18.0, 40), 18.0);
        assert!((adjusted_average_temp_by_elevation(18.0, 100) - 11.996_75).abs() < 1.0e-5);
        assert!((adjusted_average_temp_by_elevation(18.0, 200) - 0.178).abs() < 1.0e-5);
        assert!((adjusted_average_temp_by_elevation(18.0, 1000) - 0.178).abs() < 1.0e-5);
    }
}
