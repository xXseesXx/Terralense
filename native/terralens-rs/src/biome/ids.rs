pub fn name(value: u16) -> &'static str {
    BIOME_IDS.get(value as usize).copied().unwrap_or("unknown")
}
pub fn is_ocean(v: u16) -> bool {
    matches!(
        v,
        id::DEEP_OCEAN_TRENCH | id::DEEP_OCEAN | id::OCEAN | id::OCEAN_REEF
    )
}
pub fn is_flats(v: u16) -> bool {
    matches!(v, id::MUD_FLATS | id::SALT_FLATS)
}
pub fn is_flat_ice_sheet(v: u16) -> bool {
    matches!(v, id::ICE_SHEET | id::ICE_SHEET_TUYAS | id::SUBGLACIAL_LAKE)
}
pub fn is_mountains(v: u16) -> bool {
    matches!(
        v,
        id::MOUNTAINS
            | id::OCEANIC_MOUNTAINS
            | id::OLD_MOUNTAINS
            | id::VOLCANIC_MOUNTAINS
            | id::VOLCANIC_OCEANIC_MOUNTAINS
    )
}
pub fn is_low(v: u16) -> bool {
    matches!(
        v,
        id::PLAINS
            | id::HILLS
            | id::LOW_CANYONS
            | id::LOWLANDS
            | id::SALT_MARSH
            | id::MUD_FLATS
            | id::SALT_FLATS
            | id::DUNE_SEA
    )
}
pub fn has_shore(v: u16) -> bool {
    !matches!(
        v,
        id::LOW_CANYONS
            | id::CANYONS
            | id::OCEANIC_MOUNTAINS
            | id::VOLCANIC_OCEANIC_MOUNTAINS
            | id::TOWER_KARST_BAY
            | id::SUNKEN_SHIELD_VOLCANO
            | id::GLACIALLY_CARVED_OCEANIC_MOUNTAINS
            | id::GLACIATED_OCEANIC_MOUNTAINS
            | id::ICE_SHEET_OCEANIC_MOUNTAINS_EDGE
            | id::ICE_SHEET_SHIELD_VOLCANO
            | id::GLACIATED_SHIELD_VOLCANO
            | id::GUANO_ISLAND
    )
}
pub fn has_lake(v: u16) -> bool {
    !is_ocean(v)
        && !matches!(
            v,
            id::BADLANDS
                | id::ACTIVE_SHIELD_VOLCANO
                | id::DORMANT_SHIELD_VOLCANO
                | id::EXTINCT_SHIELD_VOLCANO
                | id::ANCIENT_SHIELD_VOLCANO
                | id::ICE_SHEET_MOUNTAINS
                | id::ICE_SHEET_MOUNTAINS_EDGE
                | id::ICE_SHEET_OCEANIC_MOUNTAINS
                | id::ICE_SHEET_OCEANIC_MOUNTAINS_EDGE
                | id::ICE_SHEET_SHIELD_VOLCANO
                | id::ICE_SHEET_SHORE
                | id::GLACIATED_SHIELD_VOLCANO
                | id::GLACIATED_MOUNTAINS
                | id::GLACIATED_OCEANIC_MOUNTAINS
                | id::GLACIALLY_CARVED_MOUNTAINS
                | id::GLACIALLY_CARVED_OCEANIC_MOUNTAINS
        )
}
